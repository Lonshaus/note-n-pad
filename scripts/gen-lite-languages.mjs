// Writes src/lib/editor/liteLanguages.ts: the metadata of every language in
// @codemirror/language-data (name, aliases, extensions, filename pattern) with
// none of its loaders, so the Lite build can detect and name languages without
// bundling any parser. Run it after changing that package's version, then run
// prettier on the output:
//
//   node scripts/gen-lite-languages.mjs && npx prettier --write src/lib/editor/liteLanguages.ts
//
// liteLanguages.test.ts fails when the file and the package disagree.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { languages } from '@codemirror/language-data';

const OUT_FILE = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'lib',
  'editor',
  'liteLanguages.ts',
);

const entries = languages.map((l) => {
  const parts = [
    `name: ${JSON.stringify(l.name)}`,
    `alias: ${JSON.stringify(l.alias)}`,
    `extensions: ${JSON.stringify(l.extensions)}`,
  ];
  if (l.filename !== undefined) {
    parts.push(`filename: ${String(l.filename)}`);
  }
  return `  { ${parts.join(', ')} },`;
});

fs.writeFileSync(
  OUT_FILE,
  `// Copyright © 2026 Lonshaus
// SPDX-License-Identifier: GPL-3.0-only
// Generated by scripts/gen-lite-languages.mjs from @codemirror/language-data.
/** What language detection and the save dialog read of a language: the same
 *  fields as CodeMirror's \`LanguageDescription\`, without its loader. */
export interface LanguageInfo {
  name: string;
  alias: readonly string[];
  extensions: readonly string[];
  filename?: RegExp | undefined;
}

export const LITE_LANGUAGES: readonly LanguageInfo[] = [
${entries.join('\n')}
];
`,
);
