// Generates src-tauri/windows/uninstall-cleanup.nsh, the NSIS hooks that keep
// Tauri's file-association registry writes from taking over the user's defaults
// and that clear what Tauri's uninstaller leaves behind.
//
//   node scripts/gen-nsis-hooks.mjs
//
// Measured on Windows 11: installing writes every declared extension's ProgID
// into HKCU\Software\Classes\.<ext> as that extension's default handler, backing
// up any previous owner into a "<ProgId>_backup" value. Uninstalling clears the
// default but leaves both the now-empty key and the backup value, so a full
// install/uninstall cycle leaves one orphan key per extension for good.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.join(SCRIPT_DIR, '..');
const CONFIG_FILE = path.join(REPO_ROOT, 'src-tauri', 'tauri.conf.json');
const OUTPUT_FILE = path.join(
  REPO_ROOT,
  'src-tauri',
  'windows',
  'uninstall-cleanup.nsh',
);

/** The `.<ext>` -> ProgID pairs the bundler will register, in config order. */
export function extensionPairs(conf) {
  return conf.bundle.fileAssociations.flatMap((group) =>
    group.ext.map((ext) => [ext, group.name]),
  );
}

function insertCalls(pairs, macroName) {
  return pairs
    .map(([ext, progId]) => `  !insertmacro ${macroName} "${ext}" "${progId}"`)
    .join('\n');
}

export function buildHook(conf) {
  const pairs = extensionPairs(conf);
  const offerCalls = insertCalls(pairs, 'NotePadOfferExt');
  const cleanCalls = insertCalls(pairs, 'NotePadCleanExt');
  return `; Generated by scripts/gen-nsis-hooks.mjs. Do not edit by hand.
;
; Two hooks, each covering every declared extension.
;
; NSIS_HOOK_POSTINSTALL runs after Tauri's APP_ASSOCIATE has made this app the
; default handler of each HKCU\\Software\\Classes\\.<ext> key. It hands that default
; back and registers the ProgID under OpenWithProgids instead, which is the value
; Explorer builds its "Open with" list from.
;
; NSIS_HOOK_POSTUNINSTALL removes what Tauri's uninstaller leaves behind: the
; blanked-but-present default, the "<ProgId>_backup" value, the OpenWithProgids
; entry, and the emptied key itself.
;
; HKCU, not HKLM: the installer runs in Tauri's default currentUser mode. A test
; asserts the config never switches to perMachine without this file following.

!include LogicLib.nsh

; Give up the default this install just claimed, and offer the app as a
; candidate handler instead.
;
; The default is only touched while it is still ours, so a handler the user
; picked in the meantime is left alone.
;
; A backup holding our own ProgID means a reinstall over ourselves; restoring it
; would re-take the default, so it counts as no backup.
;
; The "<ProgId>_backup" value is deliberately not deleted here. Tauri's
; uninstaller writes it back as the default; deleting it now would make that
; write blank whatever handler is current at uninstall time.
!macro NotePadOfferExt EXT PROGID
  ReadRegStr $0 HKCU "Software\\Classes\\.\${EXT}" "\${PROGID}_backup"
  ReadRegStr $1 HKCU "Software\\Classes\\.\${EXT}" ""
  \${If} $1 == "\${PROGID}"
    \${If} $0 == ""
    \${OrIf} $0 == "\${PROGID}"
      DeleteRegValue HKCU "Software\\Classes\\.\${EXT}" ""
    \${Else}
      WriteRegStr HKCU "Software\\Classes\\.\${EXT}" "" "$0"
    \${EndIf}
  \${EndIf}
  WriteRegStr HKCU "Software\\Classes\\.\${EXT}\\OpenWithProgids" "\${PROGID}" ""
!macroend

!macro NSIS_HOOK_POSTINSTALL
  Push $0
  Push $1
${offerCalls}
  Pop $1
  Pop $0
!macroend

; Restore the previous owner if there was one, otherwise take the key away.
;
; The empty default value has to go before DeleteRegKey /ifempty will do
; anything: Tauri's uninstaller blanks the default rather than removing it, so
; the key still holds one value and /ifempty refuses. Measured on Windows 11 —
; without the extra DeleteRegValue, 206 of 214 keys survived the uninstall.
;
; The OpenWithProgids subkey goes for the same reason: a leftover subkey blocks
; /ifempty exactly as a leftover value does.
;
; A key another application owns keeps a non-empty default or subkeys of its
; own, so it never reaches the delete.
!macro NotePadCleanExt EXT PROGID
  ReadRegStr $0 HKCU "Software\\Classes\\.\${EXT}" "\${PROGID}_backup"
  ReadRegStr $1 HKCU "Software\\Classes\\.\${EXT}" ""
  DeleteRegValue HKCU "Software\\Classes\\.\${EXT}" "\${PROGID}_backup"
  DeleteRegValue HKCU "Software\\Classes\\.\${EXT}\\OpenWithProgids" "\${PROGID}"
  DeleteRegKey /ifempty HKCU "Software\\Classes\\.\${EXT}\\OpenWithProgids"
  \${If} $1 == ""
    \${If} $0 != ""
      WriteRegStr HKCU "Software\\Classes\\.\${EXT}" "" "$0"
    \${Else}
      DeleteRegValue HKCU "Software\\Classes\\.\${EXT}" ""
      DeleteRegKey /ifempty HKCU "Software\\Classes\\.\${EXT}"
    \${EndIf}
  \${EndIf}
!macroend

!macro NSIS_HOOK_POSTUNINSTALL
  Push $0
  Push $1
${cleanCalls}
  Pop $1
  Pop $0
!macroend
`;
}

function main() {
  const conf = JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8'));
  const output = buildHook(conf);
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, output);
  console.log(
    `wrote ${OUTPUT_FILE}: ${extensionPairs(conf).length} extensions`,
  );
}

// Only generate when run as a script. The freshness test imports `buildHook`,
// and importing it must not rewrite the output file.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
